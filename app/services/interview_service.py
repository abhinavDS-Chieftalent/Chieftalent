"""Interview service: per-candidate question sets, phases, answers, timing.

Interview lifecycle (candidate-facing, token gated):

    not_started ──submit details──▶ details_done ──accept guidelines──▶ in_progress
         │                                                                │
         └────────── (3 tab warnings, or 30-min deadline) ──▶ aborted / completed

Phases returned by get_state():
    "details"    - pre-interview data collection form (not scored)
    "guidelines" - guidelines confirmation popup (2 checkboxes)
    "interview"  - the actual timed interview (30-minute overall deadline)
    "completed"  - finished (all questions answered, or deadline reached)
    "aborted"    - terminated (3 tab-switch warnings)

Question sets are generated per candidate (JD + resume + experience level) by
question_generator and stored on the interview row. Time limits are enforced
server-side: a question's start time is stamped when it is served, and the
submission is compared against time_limit + grace. The overall 30-minute
deadline is also enforced server-side. Refreshing the page resets nothing.
"""

import json
import logging
import secrets
import threading
from datetime import datetime, timedelta, timezone
from pathlib import Path

from .. import db
from ..config import Config
from . import question_generator

log = logging.getLogger("chieftalent.interview")

INTERVIEW_MINUTES = 30
TAB_WARNING_LIMIT = 3
# How long the continue-to-interview click waits for an in-flight AI question
# generation before reporting "preparing" (the frontend then retries). The set
# is normally already generated by this point (kicked off at OTP-confirm), so
# this wait is only a safety margin and is rarely reached.
GUIDELINES_WAIT_S = 60


def load_question_set(role):
    """Legacy static question set (kept for roles created before generation)."""
    path = Config.DATA_DIR / "interviews" / f"{role}.json"
    if not path.exists():
        raise FileNotFoundError(f"No interview question set for role '{role}' ({path})")
    return json.loads(path.read_text(encoding="utf-8"))


def load_job_posting(role):
    path = Config.DATA_DIR / "job_postings" / f"{role}.json"
    if not path.exists():
        raise FileNotFoundError(f"No job posting for role '{role}' ({path})")
    return json.loads(path.read_text(encoding="utf-8"))


def create_interview(candidate_id, role, defer_questions=False):
    """Create the interview session and (optionally) generate its question set.

    Both production callers pass defer_questions=True so the invite email is
    never delayed behind the AI call: the pipeline (auto-shortlist) and the
    manual-shortlist endpoints both send the email immediately and let
    generation run in a background thread. Generation is re-kicked at
    OTP-verify and details-submit, and accept_guidelines waits for an
    in-flight set (202 "preparing" + bounded frontend retry) - so the
    candidate always gets AI-generated questions, never defaults, while the
    email itself goes out the moment the shortlist happens.
    """
    token = secrets.token_urlsafe(24)
    db.execute(
        "INSERT INTO interviews (candidate_id, token, role, status, created_at) VALUES (?,?,?,?,?)",
        (candidate_id, token, role, "not_started", db.now_iso()),
    )
    db.execute(
        "UPDATE candidates SET interview_token=?, updated_at=? WHERE id=?",
        (token, db.now_iso(), candidate_id),
    )

    def generate():
        interview = get_interview_by_token(token)
        try:
            posting = load_job_posting(role)
            candidate = db.one("SELECT cv_text FROM candidates WHERE id=?", (candidate_id,))
            from .nim_client import NIMClient
            nim = NIMClient(Config.NIM_BASE_URL, Config.NIM_API_KEY, Config.NIM_MODEL)
            qset = question_generator.generate_question_set(nim, posting, candidate["cv_text"])
            db.execute(
                "UPDATE interviews SET question_set=? WHERE id=?",
                (json.dumps(qset, ensure_ascii=False), interview["id"]),
            )
        except Exception as e:  # noqa: BLE001 - generation retried lazily on open
            print(f"[interview] question generation deferred for {role}: {e}")

    if defer_questions:
        threading.Thread(target=generate, daemon=True).start()
    else:
        generate()
    return token


def kick_off_question_generation(interview_id):
    """Start AI question generation in the background if the set is missing.

    Called the moment the candidate verifies their email (and again when they
    submit the details form), so generation has the details-form and
    guidelines-reading time - a minute or more of human time - to finish before
    the continue-to-interview click. That click then reads an already-generated
    set and transitions instantly instead of blocking on a fresh AI call.

    Safe to call repeatedly: an existing set, or a generation already running,
    is left alone. Never blocks the caller.
    """
    interview = db.one("SELECT id, question_set FROM interviews WHERE id=?", (interview_id,))
    if not interview or interview.get("question_set"):
        return
    threading.Thread(
        target=question_generator.ensure_question_set, args=(interview_id,), daemon=True
    ).start()


def get_interview_by_token(token):
    return db.one("SELECT * FROM interviews WHERE token=?", (token,))


def _question_set_for(interview):
    """Per-candidate set if present, else the legacy static set, else the
    built-in defaults. Never raises - the interview must always be servable."""
    if interview.get("question_set"):
        return json.loads(interview["question_set"])
    try:
        return load_question_set(interview["role"])
    except (FileNotFoundError, json.JSONDecodeError):
        return question_generator.DEFAULT_QUESTIONS


def _deadline_remaining(interview):
    if not interview.get("deadline_at"):
        return None
    deadline = datetime.fromisoformat(interview["deadline_at"])
    return max(0, int((deadline - datetime.now(timezone.utc)).total_seconds()))


def _expire_if_past_deadline(interview):
    """Auto-terminate an in-progress interview whose 30 minutes are up.

    Partial answers are preserved and the evaluation runs on whatever was
    answered (same async path as a normal completion).
    """
    if interview["status"] != "in_progress" or not interview.get("deadline_at"):
        return interview
    if _deadline_remaining(interview) > 0:
        return interview
    db.execute(
        "UPDATE interviews SET status='completed', completed_at=? WHERE id=?",
        (db.now_iso(), interview["id"]),
    )
    db.execute(
        "UPDATE candidates SET status='interview_completed', updated_at=? WHERE id=?",
        (db.now_iso(), interview["candidate_id"]),
    )
    interview["status"] = "completed"
    log.info("interview %s expired at the 30-minute deadline", interview["id"])

    # Kick the evaluation asynchronously (late import avoids the circular
    # dependency: evaluation_service imports this module at load time).
    import threading

    def run():
        from . import evaluation_service
        try:
            evaluation_service.evaluate_interview(interview["id"])
        except Exception as e:  # noqa: BLE001 - logged, never fatal for state
            log.warning("deadline evaluation failed for interview %s: %s", interview["id"], e)

    threading.Thread(target=run, daemon=True).start()
    return interview


def _timed_out_flag(interview):
    """True when the interview ended because the 30 minutes ran out
    (i.e. not every question was answered)."""
    try:
        total = len(_question_set_for(interview)["questions"])
    except Exception:
        return False
    return total > 0 and (interview.get("current_index") or 0) < total


# ---------- Email verification of the interview link ----------

VERIFY_CODE_TTL_MINUTES = 10
VERIFY_RESEND_COOLDOWN_S = 55
VERIFY_MAX_ATTEMPTS = 5


def _mask_email(email):
    """john.smith@gmail.com -> j***@gmail.com (for the verify screen)."""
    if not email or "@" not in email:
        return email or ""
    local, _, domain = email.partition("@")
    return f"{local[:1]}***@{domain}"


def _verification_row(interview_id):
    return db.one("SELECT * FROM interview_verifications WHERE interview_id=?", (interview_id,))


def is_verified(interview):
    """Gate: interviews created before this feature (details already
    submitted) pass without verification; every new interview must verify
    the resume email before the details form."""
    if interview.get("details_done"):
        return True
    row = _verification_row(interview["id"])
    return bool(row and row.get("verified_at"))


def request_verification(token):
    """Email a 6-digit code to the candidate's resume address."""
    interview = get_interview_by_token(token)
    if not interview:
        return {"error": "invalid interview token"}, 404
    if interview.get("details_done") or is_verified(interview):
        return {"ok": True, "already": True}, 200

    candidate = db.one("SELECT * FROM candidates WHERE id=?", (interview["candidate_id"],))
    email = (candidate or {}).get("email") or ""
    if not email:
        return {"error": "candidate has no email on file"}, 400

    row = _verification_row(interview["id"])
    now = datetime.now(timezone.utc)
    if row and not row.get("verified_at"):
        last = datetime.fromisoformat(row["last_sent_at"])
        if (now - last).total_seconds() < VERIFY_RESEND_COOLDOWN_S:
            wait = int(VERIFY_RESEND_COOLDOWN_S - (now - last).total_seconds()) + 1
            return {"error": f"Please wait {wait}s before requesting another code"}, 429

    code = f"{secrets.randbelow(900000) + 100000}"
    expires = (now + timedelta(minutes=VERIFY_CODE_TTL_MINUTES)).isoformat()

    if row:
        db.execute(
            "UPDATE interview_verifications SET code=?, expires_at=?, attempts=0, last_sent_at=? WHERE id=?",
            (code, expires, now.isoformat(), row["id"]),
        )
    else:
        db.execute(
            "INSERT INTO interview_verifications (interview_id, code, expires_at, last_sent_at, created_at) VALUES (?,?,?,?,?)",
            (interview["id"], code, expires, now.isoformat(), now.isoformat()),
        )

    from . import email_service
    ok, detail = email_service.send_verification_email(
        email, candidate.get("name") or "", code, ttl_minutes=VERIFY_CODE_TTL_MINUTES
    )
    if not ok:
        log.error("verification email failed for interview %s: %s", interview["id"], detail)
        return {"error": "could not send the verification email, please try again"}, 502
    log.info("verification code sent for interview %s to %s", interview["id"], _mask_email(email))
    return {"ok": True, "masked_email": _mask_email(email), "expires_in_minutes": VERIFY_CODE_TTL_MINUTES}, 200


def confirm_verification(token, code):
    """Check the 6-digit code; 5 wrong attempts invalidate it."""
    interview = get_interview_by_token(token)
    if not interview:
        return {"error": "invalid interview token"}, 404
    if is_verified(interview):
        kick_off_question_generation(interview["id"])  # safety net if not started yet
        return {"ok": True, "already": True}, 200

    row = _verification_row(interview["id"])
    if not row:
        return {"error": "no code requested yet. Click Send code first"}, 400
    if row.get("verified_at"):
        kick_off_question_generation(interview["id"])
        return {"ok": True}, 200
    if row["attempts"] >= VERIFY_MAX_ATTEMPTS:
        return {"error": "too many wrong attempts. Request a new code"}, 429

    now = datetime.now(timezone.utc)
    if datetime.fromisoformat(row["expires_at"]) < now:
        return {"error": "code expired. Request a new one"}, 400

    supplied = str(code or "").strip()
    if supplied == row["code"]:
        db.execute(
            "UPDATE interview_verifications SET verified_at=? WHERE id=?",
            (now.isoformat(), row["id"]),
        )
        log.info("interview %s email verified", interview["id"])
        # The candidate is verified and actively proceeding. Start generating
        # their AI question set NOW, in the background, so it has the
        # details-form and guidelines-reading time to finish before the
        # continue-to-interview click - which then transitions instantly.
        kick_off_question_generation(interview["id"])
        return {"ok": True}, 200

    db.execute(
        "UPDATE interview_verifications SET attempts=attempts+1 WHERE id=?",
        (row["id"],),
    )
    left = VERIFY_MAX_ATTEMPTS - row["attempts"] - 1
    return {"error": f"wrong code. {max(0, left)} attempt(s) left"}, 400


def current_verification_code(interview_id):
    """Support view for HR: the active code for a candidate who says the
    email never arrived. Only while unverified and unexpired."""
    row = _verification_row(interview_id)
    if not row or row.get("verified_at"):
        return None
    if datetime.fromisoformat(row["expires_at"]) < datetime.now(timezone.utc):
        return None
    return row["code"]


def get_state(token):
    """Current interview state for the candidate-facing page."""
    interview = get_interview_by_token(token)
    if not interview:
        return None
    candidate = db.one("SELECT * FROM candidates WHERE id=?", (interview["candidate_id"],))

    if interview["status"] in ("completed", "evaluation_pending", "evaluation_completed"):
        return {"phase": "completed", "status": "completed",
                "timed_out": _timed_out_flag(interview)}

    if interview.get("aborted"):
        return {"phase": "aborted", "status": "aborted",
                "reason": interview.get("abort_reason") or "Interview terminated."}

    interview = _expire_if_past_deadline(interview)
    if interview["status"] == "completed":
        return {"phase": "completed", "status": "completed",
                "timed_out": _timed_out_flag(interview)}

    # Phase 0: verify ownership of the resume email before anything else.
    if not is_verified(interview):
        return {"phase": "verify", "status": "not_started",
                "masked_email": _mask_email(candidate.get("email"))}

    # Phase 1: pre-interview details form (data collection only, never scored).
    if not interview.get("details_done"):
        return {"phase": "details", "status": "not_started"}

    # Phase 2: guidelines confirmation.
    if not interview.get("guidelines_done"):
        return {"phase": "guidelines", "status": "not_started"}

    # Phase 3: the actual interview. Pure DB read - all questions were
    # created once (shortlist time, or the guidelines-confirm safety net).
    # No AI calls here: question transitions must be instant.
    qset = _question_set_for(interview)
    questions = qset["questions"]
    total = len(questions)

    if interview["status"] == "not_started":
        deadline_at = (datetime.now(timezone.utc) + timedelta(minutes=INTERVIEW_MINUTES)).isoformat()
        db.execute(
            "UPDATE interviews SET status='in_progress', started_at=?, deadline_at=? WHERE id=?",
            (db.now_iso(), deadline_at, interview["id"]),
        )
        db.execute(
            "UPDATE candidates SET status='interview_in_progress', updated_at=? WHERE id=?",
            (db.now_iso(), candidate["id"]),
        )
        interview["status"] = "in_progress"
        interview["deadline_at"] = deadline_at

    idx = interview["current_index"]
    if idx >= total:
        return {"phase": "completed", "status": "completed"}

    q = questions[idx]
    started_at = _ensure_pending_answer(interview["id"], idx, q)
    elapsed = (datetime.now(timezone.utc) - datetime.fromisoformat(started_at)).total_seconds()
    remaining = max(0, int(q["time_limit"] - elapsed))

    # Full question list + answered map so the candidate UI can offer
    # back-navigation and a question navigator. correct_answer / tests are
    # deliberately stripped: they must never reach the candidate's browser.
    safe_questions = [
        {
            "id": qq["id"],
            "type": qq["type"],
            "text": qq["text"],
            "require_camera": bool(qq.get("require_camera")),
            "require_mic": bool(qq.get("require_mic")),
            "choices": qq.get("choices", []),
            "guidance": qq.get("guidance", ""),
        }
        for qq in questions
    ]
    answered_rows = db.all(
        "SELECT question_index, answer_text FROM answers "
        "WHERE interview_id=? AND answer_text != ''",
        (interview["id"],),
    )
    answered = [r["question_index"] for r in answered_rows]
    answers_map = {r["question_index"]: r["answer_text"] for r in answered_rows}

    return {
        "phase": "interview",
        "status": "in_progress",
        "index": idx,
        "total": total,
        "candidate_name": candidate["name"],
        "question": {
            "id": q["id"],
            "type": q["type"],
            "text": q["text"],
            "time_limit": q["time_limit"],
            "require_camera": bool(q.get("require_camera")),
            "require_mic": bool(q.get("require_mic")),
            "choices": q.get("choices", []),
            "guidance": q.get("guidance", ""),
        },
        "questions": safe_questions,
        "answered": answered,
        "answers": answers_map,
        "remaining_seconds": remaining,
        "deadline_seconds": _deadline_remaining(interview),
        "interview_title": qset.get("title", "Interview"),
        "tab_warnings": interview.get("tab_warnings") or 0,
    }


REQUIRED_DETAIL_FIELDS = (
    "first_name", "last_name", "current_city", "hometown", "total_experience",
    "notice_period", "current_ctc", "expected_ctc", "family_members",
    "earning_members", "skills_description",
)


def save_details(token, details):
    """Phase 1: store the pre-interview form. Data collection only - never scored."""
    interview = get_interview_by_token(token)
    if not interview:
        return {"error": "invalid interview token"}, 404
    if interview.get("details_done"):
        return {"ok": True, "already": True}, 200
    if not is_verified(interview):
        return {"error": "verify your email first"}, 403

    clean = {}
    for field in REQUIRED_DETAIL_FIELDS:
        clean[field] = str(details.get(field, "") or "").strip()
    # Current company is optional (freshers may have none).
    clean["current_company"] = str(details.get("current_company", "") or "").strip()

    missing = [f for f in REQUIRED_DETAIL_FIELDS if not clean[f]]
    if missing:
        return {"error": f"missing required fields: {', '.join(missing)}"}, 400
    if len(clean["skills_description"]) < 300:
        return {"error": "please describe your three major skills in a bit more detail (at least 300 characters)"}, 400

    # Sanity bounds: hostile or fat-fingered numbers must not reach the DB.
    def _num(field, lo, hi):
        try:
            v = float(clean[field])
        except ValueError:
            return f"{field} must be a number"
        if not (lo <= v <= hi):
            return f"{field} must be between {lo:g} and {hi:g}"
        clean[field] = str(int(v)) if v == int(v) else str(v)
        return None

    for field, lo, hi in (
        ("current_ctc", 0, 100_000_000),
        ("expected_ctc", 0, 100_000_000),
        ("family_members", 1, 30),
        ("earning_members", 0, 30),
        ("notice_period", 0, 365),
        ("total_experience", 0, 50),
    ):
        err = _num(field, lo, hi)
        if err:
            return {"error": err}, 400
    if int(float(clean["earning_members"])) > int(float(clean["family_members"])):
        return {"error": "earning members cannot exceed family members"}, 400
    for field in ("first_name", "last_name", "current_city", "hometown", "current_company"):
        if len(clean[field]) > 80:
            clean[field] = clean[field][:80]

    db.execute(
        """INSERT INTO candidate_details
           (interview_id, first_name, last_name, current_city, hometown, current_company,
            total_experience, notice_period, current_ctc, expected_ctc,
            family_members, earning_members, skills_description, submitted_at)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)
           ON CONFLICT(interview_id) DO UPDATE SET
             first_name=excluded.first_name, last_name=excluded.last_name,
             current_city=excluded.current_city, hometown=excluded.hometown,
             current_company=excluded.current_company,
             total_experience=excluded.total_experience,
             notice_period=excluded.notice_period, current_ctc=excluded.current_ctc,
             expected_ctc=excluded.expected_ctc, family_members=excluded.family_members,
             earning_members=excluded.earning_members,
             skills_description=excluded.skills_description,
             submitted_at=excluded.submitted_at""",
        (interview["id"], clean["first_name"], clean["last_name"], clean["current_city"],
         clean["hometown"], clean["current_company"], clean["total_experience"],
         clean["notice_period"], clean["current_ctc"], clean["expected_ctc"],
         clean["family_members"], clean["earning_members"], clean["skills_description"],
         db.now_iso()),
    )
    db.execute("UPDATE interviews SET details_done=1 WHERE id=?", (interview["id"],))
    # Backup kick in case the OTP-confirm one did not run (e.g. already verified).
    kick_off_question_generation(interview["id"])
    return {"ok": True}, 200


def accept_guidelines(token):
    """Phase 2: candidate confirmed the guidelines. The 30-min timer starts next.

    Question generation was kicked off at OTP-confirm, so by this click the AI
    set is normally already stored and the transition is instant. If it is
    still generating (or the AI hiccuped) we wait briefly for the in-flight
    call and report 202 "preparing" so the frontend retries - we NEVER serve a
    pre-coded default set, so the candidate always gets AI-generated questions.
    """
    interview = get_interview_by_token(token)
    if not interview:
        return {"error": "invalid interview token"}, 404
    if not interview.get("details_done"):
        return {"error": "complete the information form first"}, 400
    if interview.get("guidelines_done"):
        return {"ok": True}, 200

    qset = question_generator.ensure_question_set(interview["id"], wait_s=GUIDELINES_WAIT_S)
    if not qset:
        # Still preparing (or the AI hiccuped). guidelines_done stays 0, so the
        # interview has not started and a retry is safe.
        return {"ok": False, "preparing": True}, 202
    db.execute("UPDATE interviews SET guidelines_done=1 WHERE id=?", (interview["id"],))
    return {"ok": True}, 200


def record_tab_warning(token):
    """Tab-switch warning. The 3rd warning aborts the interview."""
    interview = get_interview_by_token(token)
    if not interview:
        return {"error": "invalid interview token"}, 404
    if interview["status"] not in ("in_progress",):
        return {"error": "interview is not in progress"}, 400

    warnings = (interview.get("tab_warnings") or 0) + 1
    if warnings >= TAB_WARNING_LIMIT:
        db.execute(
            "UPDATE interviews SET tab_warnings=?, aborted=1, status='aborted', "
            "abort_reason=?, completed_at=? WHERE id=?",
            (warnings, "Interview terminated: browser tab was switched too many times.",
             db.now_iso(), interview["id"]),
        )
        db.execute(
            "UPDATE candidates SET status='interview_aborted', updated_at=? WHERE id=?",
            (db.now_iso(), interview["candidate_id"]),
        )
        return {"ok": True, "warnings": warnings, "aborted": True}, 200

    db.execute("UPDATE interviews SET tab_warnings=? WHERE id=?", (warnings, interview["id"]))
    return {"ok": True, "warnings": warnings, "aborted": False}, 200


def _ensure_pending_answer(interview_id, idx, q):
    """Create the pending answer row (stamps server-side start time) if absent."""
    existing = db.one(
        "SELECT question_started_at FROM answers WHERE interview_id=? AND question_index=?",
        (interview_id, idx),
    )
    if existing:
        return existing["question_started_at"]
    started = db.now_iso()
    db.execute(
        """INSERT INTO answers
           (interview_id, question_id, question_index, question_text, question_type,
            time_limit, question_started_at, correct_answer, created_at)
           VALUES (?,?,?,?,?,?,?,?,?)""",
        (
            interview_id, q["id"], idx, q["text"], q["type"],
            int(q["time_limit"]), started, q.get("correct_answer", ""), started,
        ),
    )
    return started


def save_answer(token, question_index, answer_text, transcript, audio_file, video_file):
    """Persist one answer. Returns dict with completion flag or an error."""
    interview = get_interview_by_token(token)
    if not interview:
        return {"error": "invalid interview token"}, 404
    if interview["status"] in ("completed", "evaluation_pending", "evaluation_completed", "aborted"):
        return {"error": "interview is already closed"}, 400
    if not (interview.get("details_done") and interview.get("guidelines_done")):
        return {"error": "interview has not been started properly"}, 400

    qset = _question_set_for(interview)
    questions = qset["questions"]
    # Answers for the CURRENT question advance the interview; answers for
    # any ALREADY-PASSED question (back-navigation) update that answer in
    # place without moving the pointer. Future questions are rejected.
    if question_index > interview["current_index"] or question_index >= len(questions):
        return {"error": "unexpected question index", "current_index": interview["current_index"]}, 400

    q = questions[question_index]
    row = db.one(
        "SELECT * FROM answers WHERE interview_id=? AND question_index=?",
        (interview["id"], question_index),
    )
    if not row:
        return {"error": "question was never served"}, 400

    is_reanswer = question_index < interview["current_index"]

    started = datetime.fromisoformat(row["question_started_at"])
    time_used = (datetime.now(timezone.utc) - started).total_seconds()
    overtime = time_used > (int(q["time_limit"]) + Config.TIME_GRACE_SECONDS)

    # Save recordings (originals are always preserved for HR review).
    audio_path = _save_blob(audio_file, interview["token"], question_index, "audio")
    video_path = _save_blob(video_file, interview["token"], question_index, "video")

    # Deterministic scoring for objective question types (mcq / yes_no).
    is_correct = None
    if q["type"] in ("mcq", "yes_no"):
        correct = (q.get("correct_answer") or "").strip()
        if correct:
            is_correct = 1 if answer_text.strip() == correct else 0

    if is_reanswer:
        # Re-answered via back-navigation: update the answer content but keep
        # the original timing facts, and never advance or complete here.
        db.execute(
            """UPDATE answers SET answer_text=?, transcript=?, is_correct=?,
               audio_path=?, video_path=? WHERE id=?""",
            (
                answer_text.strip(), transcript.strip(), is_correct,
                audio_path or row["audio_path"] or "",
                video_path or row["video_path"] or "",
                row["id"],
            ),
        )
        return {"ok": True, "completed": False, "reanswered": True,
                "next_index": interview["current_index"]}, 200

    db.execute(
        """UPDATE answers SET answer_text=?, transcript=?, time_used=?, overtime=?,
           is_correct=?, audio_path=?, video_path=? WHERE id=?""",
        (
            answer_text.strip(), transcript.strip(), round(time_used, 1), 1 if overtime else 0,
            is_correct, audio_path or "", video_path or "", row["id"],
        ),
    )

    next_index = question_index + 1
    completed = next_index >= len(questions)
    db.execute(
        "UPDATE interviews SET current_index=? WHERE id=?",
        (next_index, interview["id"]),
    )
    if completed:
        db.execute(
            "UPDATE interviews SET status='completed', completed_at=? WHERE id=?",
            (db.now_iso(), interview["id"]),
        )
        db.execute(
            "UPDATE candidates SET status='interview_completed', updated_at=? WHERE id=?",
            (db.now_iso(), interview["candidate_id"]),
        )
    return {"ok": True, "completed": completed, "next_index": next_index,
            "overtime": overtime, "time_used": round(time_used, 1)}, 200


def _save_blob(file_storage, token, question_index, kind):
    if not file_storage or not file_storage.filename:
        return ""
    ext = Path(file_storage.filename).suffix or (".webm" if kind == "video" else ".webm")
    folder = Config.RECORDINGS_DIR / token
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"q{question_index + 1}_{kind}{ext}"
    file_storage.save(str(path))
    if kind == "video":
        # Chromium MediaRecorder WebM blobs often lack final duration/cue
        # metadata. Remux on upload so both browser playback and downloaded
        # recordings can seek; failure leaves the original blob untouched.
        from .video_service import repair_webm_seek
        repair_webm_seek(path)
    return str(path)


